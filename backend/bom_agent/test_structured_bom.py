def test_build_bom_saves_rows_with_a_reference(step_file):
    bom = build_bom(step_file, SAMPLE_STEP)

    assert bom.status == "needs_review"
    assert bom.reference == f"BOM-{bom.pk:05d}"
    assert bom.rows.count() == 4
    assert list(bom.rows.values_list("line_no", flat=True)) == [1, 2, 3, 4]


def test_build_bom_with_no_parts_fails_visibly(step_file):
    bom = build_bom(step_file, b"ISO-10303-21;\nDATA;\nENDSEC;")
    assert bom.status == "failed"
    assert bom.error == "No parts found in this file."


def test_task_downloads_from_s3(step_file):
    with patch("bom_agent.tasks.download_file_from_s3", return_value=SAMPLE_STEP) as download:
        extract_bom(step_file.pk)
    download.assert_called_once_with(step_file.s3_key)
    assert Bom.objects.get(source_file=step_file).rows.count() == 4


def test_upload_enqueues_bom_extraction(auth_client, project, django_capture_on_commit_callbacks):
    upload = SimpleUploadedFile("bracket.step", SAMPLE_STEP)
    with patch("files_api.views.upload_file_to_s3", return_value="projects/x/bracket.step"), \
            patch("files_api.views.describe_file.delay"), \
            patch("bom_agent.tasks.extract_bom.delay") as delay, \
            django_capture_on_commit_callbacks(execute=True):
        response = auth_client.post(
            "/api/files/upload/", {"file": upload, "project_id": project.id}, format="multipart"
        )
    assert response.status_code == 201
    delay.assert_called_once_with(response.json()["id"])


def test_recovery_restarts_an_interrupted_extraction(step_file):
    from bom_agent.tasks import recover_orphaned_jobs

    stale = Bom.objects.create(project=step_file.project, source_file=step_file)
    with patch("bom_agent.tasks.extract_bom.delay") as delay:
        recover_orphaned_jobs()
    delay.assert_called_once_with(step_file.pk)
    assert not Bom.objects.filter(pk=stale.pk).exists()


