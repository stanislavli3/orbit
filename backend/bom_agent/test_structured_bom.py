def make_pdf(items) -> bytes:
    """A one-page PDF with text drawn at (x, y) positions — enough for pypdf's layout mode."""
    esc = lambda t: t.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")  # noqa: E731
    content = "BT /F1 10 Tf " + " ".join(f"1 0 0 1 {x} {y} Tm ({esc(t)}) Tj" for x, y, t in items) + " ET"
    objs = [
        "<< /Type /Catalog /Pages 2 0 R >>",
        "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R "
        "/Resources << /Font << /F1 5 0 R >> >> >>",
        f"<< /Length {len(content)} >>\nstream\n{content}\nendstream",
        "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    out, offsets = "%PDF-1.4\n", []
    for i, obj in enumerate(objs, start=1):
        offsets.append(len(out))
        out += f"{i} 0 obj\n{obj}\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n" + "".join(f"{o:010d} 00000 n \n" for o in offsets)
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF"
    return out.encode("latin-1")


def table_pdf(rows) -> bytes:
    columns = [40, 90, 230, 420, 470]
    return make_pdf(
        [(x, 700 - i * 14, text) for i, row in enumerate(rows) for x, text in zip(columns, row)]
    )


# ── Extraction ───────────────────────────────────────────────────────────────

def test_step_assembly_gives_one_row_per_part_with_quantities():
    rows = {r["part_number"]: r for r in extract_bom_rows(SAMPLE_STEP, "step")}

    assert set(rows) == {"ORB-1042", "ORB-1043", "SHCS-M6X16", "Part1"}  # the top assembly isn't a line
    assert rows["SHCS-M6X16"]["quantity"] == 4
    assert rows["Part1"]["quantity"] == 2
    bracket = rows["ORB-1042"]
    assert (bracket["material"], bracket["process"]) == ("6061-T6", "machined")
    assert bracket["sources"]["material"] == "STEP MATERIAL_DESIGNATION #24"
    assert bracket["confidence"] == 1.0 and bracket["flags"] == []


def test_step_flags_uncertain_rows_instead_of_guessing():
    rows = {r["part_number"]: r for r in extract_bom_rows(SAMPLE_STEP, "step")}

    assert "No material found" in rows["ORB-1043"]["flags"]
    assert rows["ORB-1043"]["material"] == ""
    assert "Part number looks auto-generated by the CAD tool" in rows["Part1"]["flags"]
    assert rows["Part1"]["confidence"] < 0.5
    screw = rows["SHCS-M6X16"]
    assert (screw["material"], screw["process"]) == ("SS 304", "purchased")
    assert screw["sources"]["material"] == "inferred from description"


def test_step_single_part_file_lists_the_part_itself():
    step = (
        b"ISO-10303-21;\nDATA;\n#1=PRODUCT('ORB-7','Shaft 4140','',(#9));\n"
        b"#2=PRODUCT_DEFINITION_FORMATION('','',#1);\n#3=PRODUCT_DEFINITION('design','',#2,#8);\nENDSEC;"
    )
    [row] = extract_bom_rows(step, "stp")
    assert (row["part_number"], row["quantity"], row["material"]) == ("ORB-7", 1, "4140")
    assert row["sources"]["quantity"] == "single part file"


def test_pdf_bom_table():
    pdf = table_pdf([
        ("ITEM", "PART NO", "DESCRIPTION", "QTY", "MATERIAL"),
        ("1", "ORB-2001", "Housing, Pump", "1", "A380 CAST"),
        ("2", "ORB-2002", "Shaft", "2", "4140"),
        ("3", "91290A320", "Screw M6x16", "8", "SS 304"),
    ])
    rows = extract_bom_rows(pdf, "pdf")

    assert [(r["part_number"], r["quantity"]) for r in rows] == [
        ("ORB-2001", 1), ("ORB-2002", 2), ("91290A320", 8),
    ]
    assert [r["process"] for r in rows] == ["casting", "machined", "purchased"]
    assert rows[1]["sources"]["quantity"].startswith("PDF BOM table, line")


def test_pdf_title_block_is_one_row_flagged_for_review():
    pdf = make_pdf([
        (400, 100, "TITLE: BRACKET, MOUNTING"),
        (400, 86, "PART NO: ORB-1042"),
        (400, 72, "MATERIAL: AL 6061-T6"),
    ])
    [row] = extract_bom_rows(pdf, "pdf")
    assert (row["part_number"], row["quantity"]) == ("ORB-1042", 1)
    assert row["confidence"] < 0.8
    assert any("title block" in f for f in row["flags"])


def test_unsupported_type_raises():
    with pytest.raises(ValueError):
        extract_bom_rows(b"", "dwg")


@pytest.mark.parametrize("text, expected", [
    ("AL 6061-T6", ("6061-T6", "aluminum")),
    ("Stainless steel 316L", ("SS 316L", "stainless")),
    ("PA66 GF30", ("PA66", "plastic")),
    ("Cover plate", None),
])
def test_find_material(text, expected):
    assert find_material(text) == expected


def test_infer_process():
    assert infer_process("Washer M6", "") == "purchased"
    assert infer_process("Enclosure", "ABS") == "injection molded"
    assert infer_process("Anything", "", is_assembly=True) == "assembly"
    assert infer_process("Mystery", "") == ""


