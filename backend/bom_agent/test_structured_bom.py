def test_list_and_detail(auth_client, bom):
    listed = auth_client.get(f"/api/bom/structured/?file_id={bom.source_file_id}").json()
    assert [b["reference"] for b in listed] == [bom.reference]

    detail = auth_client.get(f"/api/bom/structured/{bom.pk}/").json()
    assert detail["review_count"] == 2  # cover plate (no material) and Part1
    assert {r["part_number"]: r["needs_review"] for r in detail["rows"]}["ORB-1042"] is False


def test_other_users_cannot_see_a_bom(api_client, other_user, bom):
    api_client.force_authenticate(other_user)
    assert api_client.get(f"/api/bom/structured/{bom.pk}/").status_code == 404
    assert api_client.get("/api/bom/structured/").json() == []


def test_editing_a_row_clears_its_flags(auth_client, bom):
    row = bom.rows.get(part_number="Part1")
    response = auth_client.patch(
        f"/api/bom/structured/{bom.pk}/rows/{row.pk}/",
        {"part_number": "ORB-1050", "material": "6061-T6", "process": "machined"},
        format="json",
    )
    assert response.status_code == 200
    data = response.json()
    assert data["part_number"] == "ORB-1050"
    assert (data["flags"], data["confidence"], data["needs_review"]) == ([], 1.0, False)
    assert data["sources"]["material"] == "edited by testuser"
    assert data["sources"]["quantity"].startswith("STEP assembly")  # untouched fields keep their source


def test_row_quantity_must_be_positive(auth_client, bom):
    row = bom.rows.first()
    response = auth_client.patch(
        f"/api/bom/structured/{bom.pk}/rows/{row.pk}/", {"quantity": -2}, format="json"
    )
    assert response.status_code == 400


def test_delete_row(auth_client, bom):
    row = bom.rows.get(part_number="Part1")
    assert auth_client.delete(f"/api/bom/structured/{bom.pk}/rows/{row.pk}/").status_code == 204
    assert bom.rows.count() == 3


def test_approve(auth_client, bom):
    data = auth_client.post(f"/api/bom/structured/{bom.pk}/approve/").json()
    assert data["status"] == "approved"
    bom.refresh_from_db()
    assert bom.approved_by.username == "testuser"


def test_failed_bom_cannot_be_approved(auth_client, bom):
    Bom.objects.filter(pk=bom.pk).update(status="failed")
    assert auth_client.post(f"/api/bom/structured/{bom.pk}/approve/").status_code == 409


