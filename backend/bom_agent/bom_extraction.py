"""
Structured BOM extraction from STEP and PDF files (SCRUM-22).

Plain functions, no Django. ``extract_bom_rows`` returns one dict per BOM line:
part_number, description, material, process, quantity, spec, confidence (0-1),
flags (why a row needs review) and sources (where each value came from).

STEP: parts come from PRODUCT entities, quantities from the assembly structure
(NEXT_ASSEMBLY_USAGE_OCCURRENCE), materials from MATERIAL_DESIGNATION.
PDF: a BOM table found by its header row, else the drawing's title block.
Process is never stored in these files, so it is inferred from keywords.
"""

import io
import re
from collections import Counter, defaultdict

BOM_FILE_TYPES = {"step", "stp", "pdf"}

# Rows below this confidence are shown as needing review.
REVIEW_THRESHOLD = 0.8

# (regex, family). The first capture group is the grade; "T6"-style tempers are kept.
_MATERIALS = [
    (r"\b(?:AL(?:UMINUM|UMINIUM)?[\s-]*)?(6061|6063|7075|5052|2024)(?:[\s-]*(T\d+))?\b", "aluminum"),
    (r"\b(?:SS|STAINLESS(?:\s+STEEL)?)[\s-]*(303|304L?|316L?|17-4)\b", "stainless"),
    (r"\b(?:STEEL|AISI|SAE)[\s-]*(1018|1020|1045|4140|4340|A36)\b|\b(1018|1045|4140|4340)\b", "steel"),
    (r"\b(ABS|PA66|PA6|NYLON|POM|ACETAL|DELRIN|PEEK|HDPE)\b", "plastic"),
    (r"\b(BRASS|BRONZE|COPPER|TITANIUM|TI-6AL-4V)\b", "other metal"),
]


def find_material(text: str) -> tuple[str, str] | None:
    """Return (grade, family) for the first known material in ``text``."""
    upper = (text or "").upper()
    for pattern, family in _MATERIALS:
        m = re.search(pattern, upper)
        if not m:
            continue
        grade = next(g for g in m.groups() if g)
        if family == "aluminum" and m.group(2):
            grade = f"{m.group(1)}-{m.group(2)}"
        elif family == "stainless":
            grade = f"SS {grade}"
        return grade, family
    return None


def infer_process(description: str, material: str, is_assembly: bool = False) -> str:
    """Best guess at the manufacturing process from description and material."""
    if is_assembly:
        return "assembly"
    text = f"{description} {material}".upper()
    if re.search(
        r"\b(SCREW|BOLT|NUT|WASHER|RIVET|DOWEL|BEARING|SPRING|O-?RING|SHCS|ISO\s*4762|DIN\s*912)\b"
        r"|\bM\d+(?:\.\d+)?\s*X\s*\d",
        text,
    ):
        return "purchased"
    if re.search(r"\b(SHEET|GAUGE|GA)\b", text):
        return "sheet metal"
    if "CAST" in text:
        return "casting"
    found = find_material(text)
    if found and found[1] == "plastic":
        return "injection molded"
    if found:
        return "machined"
    return ""


def _looks_generated(part_number: str) -> bool:
    return bool(
        re.fullmatch(
            r"(PART|BODY|COMPONENT|ASSEMBLY|ASM|SOLID|UNNAMED|PRODUCT)[\s_-]*\d*",
            part_number,
            re.IGNORECASE,
        )
    )


def _row(part_number, description, material, quantity, sources, *, spec="", is_assembly=False):
    """Build one BOM row and score how much a reviewer should trust it."""
    part_number = (part_number or "").strip()
    description = (description or "").strip()
    material = (material or "").strip()
    flags, confidence = [], 1.0

    if not part_number:
        flags.append("No part number found")
        confidence -= 0.4
    elif _looks_generated(part_number):
        flags.append("Part number looks auto-generated by the CAD tool")
        confidence -= 0.3

    if not material and not is_assembly:
        found = find_material(description)
        if found:
            material = found[0]
            sources["material"] = "inferred from description"
            flags.append("Material inferred from description")
            confidence -= 0.1
        else:
            flags.append("No material found")
            confidence -= 0.25

    process = infer_process(description, material, is_assembly)
    if process:
        sources["process"] = "inferred from material and description"
    else:
        flags.append("Process unknown")
        confidence -= 0.1

    return {
        "part_number": part_number[:100],
        "description": description[:500],
        "material": material[:200],
        "process": process,
        "quantity": max(int(quantity), 1),
        "spec": spec[:200],
        "confidence": round(max(confidence, 0.05), 2),
        "flags": flags,
        "sources": sources,
    }


# ── STEP ─────────────────────────────────────────────────────────────────────

def _statements(text: str) -> list[str]:
    """Split the DATA section into statements on ';' outside quoted strings."""
    start = text.upper().find("DATA;")
    body = text[start + 5 :] if start >= 0 else text
    out, buf, in_str = [], [], False
    for ch in body:
        if ch == "'":
            in_str = not in_str  # '' (escaped quote) toggles twice
        if ch == ";" and not in_str:
            out.append("".join(buf).strip())
            buf = []
        else:
            buf.append(ch)
    return out


def _args(s: str) -> list[str]:
    """Split an entity's arguments on top-level commas."""
    parts, cur, depth, in_str = [], [], 0, False
    for ch in s:
        if ch == "'":
            in_str = not in_str
        elif not in_str:
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
            elif ch == "," and depth == 0:
                parts.append("".join(cur).strip())
                cur = []
                continue
        cur.append(ch)
    parts.append("".join(cur).strip())
    return parts


def _str(arg: str) -> str:
    if len(arg) >= 2 and arg[0] == "'" and arg[-1] == "'":
        return arg[1:-1].replace("''", "'").strip()
    return ""


def _ref(arg: str) -> int | None:
    m = re.fullmatch(r"#(\d+)", arg.strip())
    return int(m.group(1)) if m else None


_ENTITY = re.compile(r"#(\d+)\s*=\s*([A-Z0-9_]+)\s*\((.*)\)\s*$", re.S | re.I)


def extract_bom_from_step(data: bytes) -> list[dict]:
    entities = {}
    for statement in _statements(data.decode("utf-8", errors="ignore")):
        m = _ENTITY.match(statement)
        if m:
            entities[int(m.group(1))] = (m.group(2).upper(), _args(m.group(3)))

    def of_type(prefix):
        return [(i, a) for i, (name, a) in entities.items() if name.startswith(prefix)]

    products = {i: a for i, a in of_type("PRODUCT") if entities[i][0] == "PRODUCT"}
    formation_product = {i: _ref(a[2]) for i, a in of_type("PRODUCT_DEFINITION_FORMATION") if len(a) > 2}
    pd_product = {
        i: formation_product.get(_ref(a[2]))
        for i, a in of_type("PRODUCT_DEFINITION")
        if entities[i][0] == "PRODUCT_DEFINITION" and len(a) > 2
    }
    shape_pd = {i: _ref(a[2]) for i, a in of_type("PRODUCT_DEFINITION_SHAPE") if len(a) > 2}

    materials = {}
    for i, a in of_type("MATERIAL_DESIGNATION"):
        for ref in (int(r) for r in re.findall(r"#(\d+)", a[1] if len(a) > 1 else "")):
            product = pd_product.get(shape_pd.get(ref, ref))
            if product:
                materials[product] = (_str(a[0]), i)

    children = defaultdict(Counter)
    for i, a in of_type("NEXT_ASSEMBLY_USAGE_OCCURRENCE"):
        if len(a) > 4:
            parent, child = pd_product.get(_ref(a[3])), pd_product.get(_ref(a[4]))
            if parent and child:
                children[parent][child] += 1

    is_assembly_file = bool(children)
    quantity = Counter()
    child_ids = {c for counts in children.values() for c in counts}
    roots = [p for p in products if p not in child_ids]

    def walk(product, multiplier, depth=0):
        if depth > 20:  # guards against a malformed, cyclic file
            return
        for child, count in children.get(product, {}).items():
            quantity[child] += multiplier * count
            walk(child, multiplier * count, depth + 1)

    for root in roots:
        walk(root, 1)

    # An assembly's BOM lists what is inside it; a single part lists itself.
    listed = [p for p in products if p in child_ids] if is_assembly_file else list(products)

    rows = []
    for pid in listed:
        a = products[pid]
        part_number, name = _str(a[0]), _str(a[1])
        description = name if name and name != part_number else _str(a[2]) or name
        material, material_id = materials.get(pid, ("", None))
        sources = {
            "part_number": f"STEP PRODUCT #{pid}",
            "description": f"STEP PRODUCT #{pid}",
            "quantity": (
                f"STEP assembly structure ({quantity[pid]} occurrences)" if is_assembly_file else "single part file"
            ),
        }
        if material:
            sources["material"] = f"STEP MATERIAL_DESIGNATION #{material_id}"
        rows.append(
            _row(part_number, description, material, quantity[pid] or 1, sources, is_assembly=bool(children.get(pid)))
        )
    return rows


# ── PDF ──────────────────────────────────────────────────────────────────────

_COLUMNS = {
    "part_number": ("PART NO", "PART NUMBER", "PART #", "P/N", "PN"),
    "description": ("DESCRIPTION", "DESC", "TITLE"),
    "quantity": ("QTY", "QUANTITY"),
    "material": ("MATERIAL", "MATL"),
    "spec": ("SPEC", "TOLERANCE", "FINISH"),
}


def _column_field(cell: str) -> str | None:
    cell = cell.upper().strip().rstrip(".")
    for field, names in _COLUMNS.items():
        if cell in names:
            return field
    return None


def _pdf_lines(data: bytes) -> list[str]:
    from pypdf import PdfReader

    lines = []
    for page in PdfReader(io.BytesIO(data)).pages[:20]:
        try:
            text = page.extract_text(extraction_mode="layout")
        except Exception:
            text = page.extract_text() or ""
        lines.extend(text.splitlines())
    return lines


def _parse_table(lines: list[str]) -> list[dict]:
    """Rows of the first table whose header names a part number and a quantity."""
    for h, line in enumerate(lines):
        columns = [_column_field(c) for c in re.split(r"\s{2,}", line.strip())]
        if "part_number" not in columns or "quantity" not in columns:
            continue
        rows, misses = [], 0
        for n, row_line in enumerate(lines[h + 1 :], start=h + 2):
            cells = re.split(r"\s{2,}", row_line.strip())
            if len(cells) != len(columns) or not row_line.strip():
                misses += 1
                if rows and misses >= 2:
                    break
                continue
            misses = 0
            values = {f: c for f, c in zip(columns, cells) if f}
            qty = values.get("quantity", "")
            source = f"PDF BOM table, line {n}"
            sources = {f: source for f in values}
            row = _row(
                values.get("part_number"),
                values.get("description"),
                values.get("material"),
                int(qty) if qty.isdigit() else 1,
                sources,
                spec=values.get("spec", ""),
            )
            if not qty.isdigit():
                row["flags"].append(f"Quantity '{qty}' not a number; assumed 1")
                row["confidence"] = round(max(row["confidence"] - 0.3, 0.05), 2)
            rows.append(row)
        if rows:
            return rows
    return []


def _parse_title_block(text: str) -> list[dict]:
    """A single-part drawing: part number and material from the title block."""
    pn = re.search(r"(?:PART\s*(?:NO|NUMBER|#)|P/N|DWG\.?\s*NO)\.?\s*[:#]?\s*([A-Z0-9][A-Z0-9._-]{2,})", text, re.I)
    if not pn:
        return []
    material = re.search(r"(?:MATERIAL|MATL)\.?\s*:?\s*([^\n]{2,40}?)(?:\s{2,}|\n|$)", text, re.I)
    title = re.search(r"TITLE\.?\s*:?\s*([^\n]{2,60}?)(?:\s{2,}|\n|$)", text, re.I)
    sources = {"part_number": "PDF title block", "quantity": "assumed 1 (single-part drawing)"}
    if material:
        sources["material"] = "PDF title block"
    if title:
        sources["description"] = "PDF title block"
    row = _row(
        pn.group(1),
        title.group(1) if title else "",
        material.group(1) if material else "",
        1,
        sources,
    )
    row["flags"].append("No BOM table; read the title block and assumed quantity 1")
    row["confidence"] = round(max(row["confidence"] - 0.25, 0.05), 2)
    return [row]


def extract_bom_from_pdf(data: bytes) -> list[dict]:
    lines = _pdf_lines(data)
    return _parse_table(lines) or _parse_title_block("\n".join(lines))


def extract_bom_rows(data: bytes, file_type: str) -> list[dict]:
    file_type = (file_type or "").lower()
    if file_type in ("step", "stp"):
        return extract_bom_from_step(data)
    if file_type == "pdf":
        return extract_bom_from_pdf(data)
    raise ValueError(f"BOM extraction does not support .{file_type} files")
